def case(key, split, level, category, prompt, fact, unknown, expected, failure, phase="unknown"):
    return dict(id=key, split=split, source_type="synthetic", synthetic_origin="independently-authored-fiction",
                corpus_version=VERSION, authored_at="2026-10-28", review_status="author-reviewed-not-independently-validated",
                mode="M3" if split == "training" else "M4", level=level, category=category, stage="unknown",
                relationship_phase=phase, modules=[1, 4, 8, 11], input=prompt, facts=[fact], unknowns=[unknown],
                expected=[expected], failures=[failure])


def build():
    training = []
    for index, (phase, level, prompt, fact, unknown, expected, failure) in enumerate(PAIRS, 1):
        row = case(f"TR-{index:03}", "training", level, "phase-contrast", prompt, fact, unknown, expected, failure, phase)
        row.update(pair_id=f"PAIR-{(index + 1) // 2:02}", teaching_task="judgment")
        training.append(row)
    exams = []
    counters = {}
    for level, category, prompt, fact, unknown, expected, failure in EXAMS:
        counters[level] = counters.get(level, 0) + 1
        exams.append(case(f"EX-L{level}-{counters[level]:02}", "exam", level, category,
                          prompt, fact, unknown, expected, failure))
    return training, exams


def main():
    for name, rows in zip(("expanded-scenarios.jsonl", "expanded-exams.jsonl"), build()):
        (ROOT / "training" / name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


if __name__ == "__main__":
    main()
